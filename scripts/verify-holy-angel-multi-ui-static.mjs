import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {fileURLToPath} from 'node:url';
const file=p=>readFileSync(fileURLToPath(new URL('../'+p,import.meta.url)));
const html=file('holy-angel-multi-planner-test.html').toString('utf8');
const js=file('js/holy-angel-multi-planner-ui.mjs').toString('utf8');
const old=file('holy-angel-planner-test.html').toString('utf8');
const sprite=file('assets/holy-angel/relic-sprite.jpg');
const checks=[];
const check=(name,condition)=>checks.push([name,!!condition]);
check('HTML Japanese language',html.includes('<html lang="ja">'));
check('Mobile viewport',html.includes('name="viewport"'));
check('Noindex test only',html.includes('content="noindex,nofollow"'));
check('External module only',html.includes('src="./js/holy-angel-multi-planner-ui.mjs"'));
check('All 5 shared part pools',['arm','feet','accessory','head','body'].every(k=>html.includes('name="parts-'+k+'"')));
check('All 4 real relic pools',['chalice','medal','wing','fruit'].every(k=>html.includes('name="owned-'+k+'"')));
check('In-game sprite in multiple UI',html.includes('assets/holy-angel/relic-sprite.jpg'));
check('In-game sprite in single UI',old.includes('assets/holy-angel/relic-sprite.jpg'));
check('All four distinct sprite positions',['background-position:0 0','background-position:-36px 0','background-position:-72px 0','background-position:-108px 0'].every(p=>html.includes(p)));
check('Sprite JPEG SOI/EOI',sprite[0]===255&&sprite[1]===216&&sprite.at(-2)===255&&sprite.at(-1)===217);
const sha=createHash('sha1').update('blob '+sprite.length+'\0').update(sprite).digest('hex');
check('Sprite bytes match cropped user-provided image',sha==='8064f18aec4f2aab4a62976c7b255d29f5d41176');
check('No external analytics/ads',!/googlesyndication|adsbygoogle|google-analytics/.test(html+js));
check('No network APIs',!/(fetch\(|XMLHttpRequest|sendBeacon|WebSocket)/.test(js));
check('No unsafe dynamic HTML',!/\.innerHTML\s*=|insertAdjacentHTML/.test(js));
check('Priority up and down',html.includes('data-action="up"')&&html.includes('data-action="down"'));
check('Can add and remove plan',html.includes('data-action="add"')&&html.includes('data-action="remove"'));
check('Explicit shared parts in combined model',js.includes('planPrioritizedSharedEquipment({plans,partsBySlot,ownedRelics})'));
check('Independent plan comparison',js.includes('planEquipmentParts({...p,ownedParts:partsBySlot[p.slot]})'));
check('One real inventory per slot',js.includes("name=\"parts-"));
check('4-type forecast through shared shortages',js.includes('needs:combined.shortages'));
check('Stop/complete strategy selector',html.includes('value="stop-on-target"')&&html.includes('value="complete-cycle"'));
check('Weekly free start logic',js.includes('getForecastFreeSchedule'));
check('No cloud save claimed',html.includes('PCとスマホの同期')&&html.includes('未実装'));
check('Local-only save button',html.includes('data-action="save"')&&js.includes('localStorage.setItem'));
check('Local-only load button',html.includes('data-action="load"')&&js.includes('localStorage.getItem'));
check('JSON export',js.includes('new Blob(')&&html.includes('data-action="export"'));
check('JSON import',html.includes('id="import-json"')&&js.includes('await file.text()'));
check('Versioned saved draft',js.includes("const STORAGE_KEY='holy-angel-multi-plan-test-v1'")&&js.includes('version:1'));
check('Bound plan count',js.includes('const MAX_PLANS=8'));
check('Bound import size',js.includes('64000'));
check('Dont mutate real game inventory on reorder',js.includes('実際の在庫は消費しません'));
check('User edit state preserved before reorder',js.includes('syncFromScreen();')&&js.includes('draft.plans[i],draft.plans[next]'));
check('No automated plan recommendation',html.includes('先に育てたい順番'));
check('Separate expected cost when not complete',js.includes('forecast.expectedDiamondsToComplete===null'));
check('Inputs given at least target and current',html.includes('data-field="target"')&&html.includes('data-field="current"'));
check('User can name two physical items',html.includes('data-field="equipmentId"'));
check('Manual levels above 530',html.includes('data-field="steps"'));
check('Result rows use textContent',js.includes('el.textContent=String(text)'));
const ids=[...js.matchAll(/byId\('([^']+)'\)/g)].map(m=>m[1]);
check('Every explicit element reference exists',ids.every(id=>html.includes('id="'+id+'"')));
check('Result tables for combined and single',html.includes('id="combined-details"')&&html.includes('id="individual-details"'));
check('Results explicitly marked assumptions',html.includes('独立と仮定')&&html.includes('装備完成を保証しません'));
const failures=checks.filter(x=>!x[1]);
if(failures.length)throw new Error('Failed: '+failures.map(x=>x[0]).join(', '));
console.log('PASS '+checks.length+' multi-plan UI static and screenshot-sprite checks');
