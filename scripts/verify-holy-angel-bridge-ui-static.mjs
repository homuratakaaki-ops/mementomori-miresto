import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const source=p=>readFileSync(fileURLToPath(new URL('../'+p,import.meta.url)),'utf8');
const html=source('holy-angel-linked-test.html'),js=source('js/holy-angel-bridge-ui.mjs'),core=source('js/holy-angel-plan-actual-bridge.mjs');
let count=0;
function yes(title,check){assert.ok(check,title);count++;}
yes('Only a development test',html.includes('開発用テスト')&&html.includes('noindex,nofollow'));
yes('Mobile viewport',html.includes('name="viewport"'));
yes('Distinct source options',html.includes('value="plans"')&&html.includes('value="actuals"'));
yes('Uses existing v1 and v2 without edits',core.includes('holy-angel-multi-plan-test-v1')&&core.includes('holy-angel-actuals-test-v2'));
yes('Four in-game relic icons',html.includes('relic-sprite.jpg')&&js.includes('RELIC_KEYS.entries()'));
yes('Load only via button or file',html.includes('data-action="load-plans"')&&html.includes('data-action="load-actuals"'));
yes('Two separate import controls',html.includes('id="plan-file"')&&html.includes('id="actual-file"'));
yes('No ads or analytics',!/adsbygoogle|analytics|googlesyndication/.test(html+js));
yes('No remote network use',!/fetch\s*\(|XMLHttpRequest|sendBeacon|WebSocket/.test(js));
yes('No localStorage writes',!js.includes('localStorage.setItem')&&!js.includes('localStorage.removeItem')&&!js.includes('localStorage.clear()'));
yes('No direct HTML injection',!/innerHTML\s*=|insertAdjacentHTML/.test(js));
yes('No API secret or link',!/#token|Authorization|api\.cloudflare/.test(js));
yes('No auto merge in backend',!core.includes('...plan.partsBySlot,...actual'));
yes('Must reject unclaimed checkpoints',core.includes('pendingClaims.length'));
yes('Requires forward start date',core.includes('parseJstLocal(plan.settings.startAt)<parseJstLocal(actualState.at)'));
yes('Validates both imported files',js.includes('normalizeLegacyPlans(decoded)')&&js.includes('validateActualBundle(decoded)'));
yes('Rejects oversized files',js.includes('file.size>limit'));
yes('No silently accepted invalid data',js.includes('acceptPlan(raw)')&&js.includes('acceptActual(raw)'));
yes('Read-only presentation',html.includes('上書きしません')&&js.includes('元のデータが変更されました'));
yes('Displays both actual and plan mode',js.includes('確認済みの実績')&&js.includes('計画に入力した所持数'));
yes('Shows difference in confirmed count',js.includes('differsFromPlanEntry'));
yes('Predict only from bridge',js.includes('bridgePlansAndActuals'));
yes('Uses display-only text',js.includes('.textContent='));
yes('No JSON jargon on user page',!html.includes('JSON'));
const references=[...js.matchAll(/id\('([^']+)'\)/g)].map(m=>m[1]);
yes('All explicit result IDs present',references.every(x=>html.includes('id="'+x+'"')));
console.log('PASS '+count+' read-only bridge UI structure checks');
