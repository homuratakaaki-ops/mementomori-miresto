import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const read=p=>readFileSync(fileURLToPath(new URL('../'+p,import.meta.url)),'utf8');
const html=read('holy-angel-combined-test.html'),js=read('js/holy-angel-combined-ui.mjs');
let n=0;function ok(label,condition){assert.ok(condition,label);n++;}
ok('Mobile document',html.includes('name="viewport"'));
ok('Noindex development only',html.includes('noindex,nofollow')&&html.includes('開発用テスト'));
ok('Legacy data not overwritten',html.includes('以前の育成計画と実績は上書きしません'));
ok('No cloud implementation',html.includes('クラウド保存は未実装'));
ok('Avoid technical JSON words',!html.includes('JSON'));
ok('All source file controls', ['plan-file','actual-file','combined-file'].every(k=>html.includes('id="'+k+'"')));
ok('Explicit v3 creation',html.includes('data-action="create-v3"'));
ok('Export and import',html.includes('data-action="export-v3"')&&html.includes('data-action="load-v3"'));
ok('Separate saving action',html.includes('data-action="save-v3"'));
ok('New revision source module',js.includes("from './holy-angel-combined-workspace.mjs'"));
ok('Old v1/v2 keys read',js.includes('PLAN_V1_KEY')&&js.includes('ACTUAL_V2_KEY'));
ok('Distinct v3 storage',js.includes('COMBINED_WORKSPACE_KEY'));
ok('Blocked stale updates',js.includes('currentStored!==baseSaved'));
ok('No old storage write',!js.includes('localStorage.setItem(PLAN_V1_KEY')&&!js.includes('localStorage.setItem(ACTUAL_V2_KEY'));
ok('No externally sent data',!/fetch\s*\(|XMLHttpRequest|WebSocket|sendBeacon/.test(js));
ok('No HTML injection',!/\.innerHTML\s*=|insertAdjacentHTML/.test(js));
ok('Explicit record undo',js.includes('appendCombinedActualEvent')&&js.includes('undoLastCombinedEvent'));
ok('All event types', ['draw','claim','switch','exchange','weekly-reset'].every(x=>html.includes('value="'+x+'"')));
ok('Priority change',js.includes('moveCombinedPlan'));
ok('Read-only previous source',js.includes('createCombinedWorkspace({planV1:plans,actualV2:actuals})'));
ok('Model blocks uncertainty',js.includes('inspectCombinedWorkspace'));
ok('Errors visible',html.includes('id="bridge-error" role="alert"'));
ok('All referenced IDs exist',[...js.matchAll(/el\('([^']+)'\)/g)].every(x=>html.includes('id="'+x[1]+'"')));
console.log('PASS '+n+' combined workspace UI static checks');
