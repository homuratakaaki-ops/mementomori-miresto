import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const file=path=>readFileSync(fileURLToPath(new URL('../'+path,import.meta.url)),'utf8');
const html=file('holy-angel-actuals-test.html');
const js=file('js/holy-angel-actuals-ui.mjs');
let count=0;
const test=(name,ok)=>{assert.ok(ok,name);count++};
test('Japanese document',html.includes('<html lang="ja">'));
test('mobile viewport',html.includes('name="viewport"'));
test('noindex page',html.includes('noindex,nofollow'));
test('explicit testing only',html.includes('開発用テスト'));
test('real game not modified',html.includes('実際のゲーム内操作はしません'));
test('no cloud implied',html.includes('クラウド同期')&&html.includes('未実装'));
test('replay import',js.includes("from './holy-angel-actual-log.mjs'"));
test('uses local v2 distinct storage key',js.includes("holy-angel-actuals-test-v2"));
test('actual snapshot fields',[
'snapshotAt','initialSelected','initialGauge','initialSwitches','initialTickets','initialDiamonds','initialUsedToday','claimed10','claimed25'
].every(k=>html.includes('name="'+k+'"')));
test('relic 4 inputs',['chalice','medal','wing','fruit'].every(k=>html.includes('name="relic-'+k+'"')));
test('parts 5 inputs',['arm','feet','accessory','head','body'].every(k=>html.includes('name="part-'+k+'"')));
test('game icon positions',[-36,-72,-108].every(v=>html.includes('background-position:'+v+'px 0')));
test('one image sprite',html.includes('assets/holy-angel/relic-sprite.jpg'));
test('draw fields',html.includes('drawCount')&&html.includes('drawTickets')&&html.includes('drawFree'));
test('claim fields',html.includes('claimMilestone')&&html.includes('claimWon'));
test('switch fields',html.includes('switchMethod')&&html.includes('abandonPending'));
test('exchange fields',html.includes('exchangeSlot')&&html.includes('exchangeCount'));
test('weekly-reset field',html.includes('resetSelected'));
test('event controls',[...['record','undo','save','load','export']].every(v=>html.includes('data-action="'+v+'"')));
test('JSON upload',html.includes('id="actual-import"'));
test('no external tracker',!/googlesyndication|adsbygoogle|analytics|gtag/.test(html+js));
test('no network',!/fetch\s*\(|XMLHttpRequest|WebSocket|sendBeacon/.test(js));
test('no raw HTML injection',!/\.innerHTML\s*=|insertAdjacentHTML/.test(js));
test('results textContent',js.includes('.textContent='));
test('atomic test before add',js.includes('preview(readSnapshot(),next)'));
test('undo replay validation',js.includes("recordedEvents.slice(0,-1);preview(readSnapshot(),next)"));
test('undo confirmation',js.includes("confirm('最後の1件を取り消します"));
test('explicit save only',js.includes("localStorage.setItem(SAVE_KEY,json)"));
test('no legacy overwrites',!js.includes('holy-angel-multi-plan-test-v1'));
test('64KB and 300 events guard',js.includes('MAX_BYTES=64000,MAX_EVENTS=300'));
test('validate import before restore',js.includes('validateRestored(json)')&&js.includes('preview(o.snapshot,o.events)'));
test('JSON version 2',js.includes('schemaVersion:2'));
test('non-success state remains',js.includes('変更あり。端末内保存はまだです'));
test('max snapshot diamonds or null',js.includes("coins===''?undefined"));
test('50 draw reward explicit',html.includes('50回（確定）'));
test('pending shows unknown rewards',js.includes('pendingClaims.map'));
test('event list rendered from state',js.includes('showHistory(recordedEvents)'));
test('not a prediction',html.includes('未来の予測ではなく'));
