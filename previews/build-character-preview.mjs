#!/usr/bin/env node
/**
 * 確認用キャラページを、検証済み canonical JSON から静的生成する。
 * Usage: node previews/build-character-preview.mjs <mementomori-skills.json> <character-id> <preview-key>
 *
 * 公開用 data/ は変更しない。公開前の作業ツリーにある canonical を入力にする。
 * 本文の正は同じ canonical、描画の正は js/render-character.js のままとし、
 * 別のキャラデータやスキルの描画ロジックをここに保持しない。
 * 出力は previews/<preview-key>/<character-id>.html のみ。
 * URLを知る人は閲覧できる。認証・アクセス制限ではない。
 * 通常掲載へ進める際は通常のキャラ生成を行い、確認用ページを撤去する。
 */
import assert from "node:assert/strict";
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { versioned } from "../scripts/asset-version.mjs";

const require = createRequire(import.meta.url);
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const renderer = require(join(ROOT, "js/render-character.js"));
const gacha = require(join(ROOT, "js/gacha-status.js"));
const analytics = require(join(ROOT, "js/render-analytics.js"));
const [source, id, key, ...extra] = process.argv.slice(2);
assert(source && id && key && !extra.length,
  "Usage: node previews/build-character-preview.mjs <mementomori-skills.json> <character-id> <preview-key>");
assert.equal(basename(source), "mementomori-skills.json", "入力は検証済み canonical JSON に限る");
assert.match(id, /^[a-z0-9_]+$/);
assert.match(key, /^[a-z0-9][a-z0-9-]+$/);
const data = JSON.parse(readFileSync(resolve(source), "utf8"));
const characters = data.characters.filter((item) => item.id === id);
assert.equal(characters.length, 1, "対象キャラは1件だけ必要");
const character = characters[0];
const skills = renderer.selectSkills(data, id);
assert.equal(skills.length, 4, "4スキルの検証済みキャラが必要");
assert(skills.every((skill) => skill.flow?.length), "各スキルに flow が必要");
const terms = JSON.parse(readFileSync(join(ROOT, "data/terms.json"), "utf8")).terms;
const now = gacha.buildNow(process.env);
const metaHtml = renderer.renderMetaHtml(character, { items: [] }, now);
const skillListHtml = renderer.renderSkillList(skills, terms);
const e = renderer.escapeHtml;
const html = `<!doctype html>
<!-- Generated by previews/build-character-preview.mjs. Do not edit this HTML directly. -->
<html lang="ja">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex,nofollow,noarchive">
  <meta name="referrer" content="no-referrer">
  <title>確認用 | ${e(renderer.pageTitle(character))}</title>
  <meta name="description" content="確認用ページ。${e(renderer.pageDescription(character, skills))}">
  <link rel="icon" href="/favicon.ico" sizes="32x32">
  <link rel="icon" type="image/png" href="/assets/miresto/miresto-icon-32.png" sizes="32x32">
  <link rel="apple-touch-icon" href="/assets/miresto/miresto-icon-180.png">
  <link rel="stylesheet" href="/${versioned("assets/character-page.css")}">
${metaHtml.includes(" data-gacha-timeline=") ? `  <script src="/${versioned("js/gacha-switch.js")}" defer></script>\n` : ""}${analytics.renderAnalyticsHead(null, "  ")}
</head>
<body data-character-page data-character-id="${e(character.id)}" data-attribute="${e(character.attribute || "")}" data-prerendered data-analytics="off" data-ads="off">
  <header class="page-header">
    <div class="header-inner">
      <a class="top-link" href="/">トップ</a>
      <a class="top-link" href="/pages/characters/index.html">キャラ一覧へ戻る</a>
      <p class="eyebrow">CHARACTER SKILL DATA</p>
      <h1 id="characterName">${e(character.name)}</h1>
      <p class="role" id="roleMemo">${e(renderer.roleMemoText(character))}</p>
      <div class="meta-row" id="characterMeta">${metaHtml}</div>
    </div>
  </header>

  <main>
    <section class="note-panel" aria-label="確認用ページのご案内">
      <strong>確認用ページ（通常掲載前）</strong><br>
      TOP・キャラ一覧・サイトマップには掲載していません。URLを知っている方は閲覧できます。<br>
      内容と表示の確認用です。広告・アクセス解析は停止しています。
    </section>
    <section class="skill-list" id="skillList">${skillListHtml}</section>
  </main>

  <footer>
    <div class="footer-inner">
      <span>ミレストのメメントモリ分析データ室 / 非公式ファンサイト</span>
      <nav class="footer-links" aria-label="サイト内のページ">
        <a href="/">トップ</a>
        <a href="/pages/characters/index.html">キャラ一覧</a>
        <a href="/compare-prototype.html">スキル比較DB</a>
        <a href="/pages/guide/">このサイトでできること</a>
        <a href="/privacy.html">プライバシーポリシー</a>
        <a href="/disclaimer.html">免責事項</a>
        <a href="/about.html">このサイトについて</a>
        <a href="/contact.html">お問い合わせ</a>
      </nav>
    </div>
  </footer>
</body>
</html>
`.replace(/[\t ]+$/gm, "");

assert.equal((html.match(/<article class="skill-card"/g) || []).length, 4);
assert(!/googletagmanager|googlesyndication|adsbygoogle|gtag\(/.test(html), "計測・広告を含めない");
assert(!/character-page\.js|render-character\.js|mementomori-skills\.json/.test(html), "公開 JSON の取得・再描画はしない");
assert(!/rel="canonical"|property="og:/.test(html), "正式公開先や共有カードを宣言しない");
assert(!/notion\.(?:com|so)|library_file|sediment:|\/workspace\/|\/home\/|Sentinel_/.test(html), "内部資料を公開しない");
const output = join(ROOT, "previews", key, `${id}.html`);
mkdirSync(dirname(output), { recursive: true });
const changed = !existsSync(output) || readFileSync(output, "utf8") !== html;
if (changed) writeFileSync(output, html);
console.log(`確認用: previews/${key}/${id}.html (${changed ? "更新" : "変更なし"}) / スキル4件 / 判定時刻 ${now}`);
